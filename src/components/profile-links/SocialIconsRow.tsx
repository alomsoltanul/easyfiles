export default function SocialIconsRow({ socials, textColor = '#ffffff', accentColor = '#38bdf8' }: SocialIconsRowProps) {
  const activeSocials = SOCIAL_ITEMS.filter((item) => {
    const val = socials[item.key];
    return val && val.trim().length > 0;
  });

  if (activeSocials.length === 0) return null;

  return (
    <div className="flex flex-wrap items-center justify-center gap-3 my-4">
      {activeSocials.map((item) => {
        const rawVal = socials[item.key] || '';
        const href = item.urlPrefix(rawVal.trim());

        return (
          <a
            key={item.key}
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={item.label}
            className="p-2.5 rounded-full transition-all duration-200 transform hover:scale-110 active:scale-95 bg-black/15 hover:bg-black/25 backdrop-blur-sm shadow-sm"
            style={{ color: textColor }}
          >
            <svg
              className="w-5 h-5 fill-current"
              viewBox="0 0 24 24"
              role="img"
              aria-hidden="true"
            >
              {item.svg}
            </svg>
          </a>
        );
      })}
    </div>
  );
}
